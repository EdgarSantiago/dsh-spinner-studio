"""Original geometric activity icons; no third-party artwork or network assets.
Time-based loops: uniform frame timing, no flashes, static reduced-motion posters.
"""
from pathlib import Path
from math import sin, cos, pi
import base64
import json
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'assets' / 'gifs'
OUT.mkdir(parents=True, exist_ok=True)
SIZE = 64

def frame(kind, phase):
    image = Image.new('P', (SIZE, SIZE), 0)
    image.putpalette([0, 0, 0, 255, 255, 255] + [0, 0, 0] * 254)
    image.info['transparency'] = 0
    draw = ImageDraw.Draw(image)
    def dot(x, y, radius):
        draw.ellipse((round(x-radius), round(y-radius), round(x+radius), round(y+radius)), fill=1)
    if kind == 'dots':
        for i, x in enumerate((14, 32, 50)):
            y = 32 - 7 * sin(2*pi*phase - i*2*pi/3)
            dot(x, y, 5)
    elif kind == 'orbit':
        draw.ellipse((12, 12, 52, 52), outline=1, width=3)
        dot(32, 32, 5)
        angle = 2*pi*phase-pi/2
        dot(32+20*cos(angle), 32+20*sin(angle), 6)
    elif kind == 'bars':
        for i in range(5):
            height = 10 + 22*(0.5+0.5*sin(2*pi*phase-i*pi/3))
            x = 8+i*10
            draw.rounded_rectangle((x, round(32-height/2), x+6, round(32+height/2)), radius=3, fill=1)
    elif kind == 'pulse':
        radius = 14 + 6*(0.5-0.5*cos(2*pi*phase))
        points = [(32,32-radius),(36,28),(32+radius,32),(36,36),(32,32+radius),(28,36),(32-radius,32),(28,28)]
        draw.polygon(points, fill=1)
        dot(12, 12, 2)
        dot(52, 52, 2)
    return image

presets = []
for kind in ('dots', 'orbit', 'bars', 'pulse'):
    count = 24 if kind == 'pulse' else 16
    frames = [frame(kind, i/count) for i in range(count)]
    animated = OUT / f'{kind}.gif'
    still = OUT / f'{kind}-still.gif'
    frames[0].save(animated, save_all=True, append_images=frames[1:], duration=80, loop=0, transparency=0, disposal=2, optimize=False)
    frames[0].save(still, transparency=0, optimize=False)
    with Image.open(animated) as check:
        # GIF encoders can merge identical raster frames, preserving total timing.
        assert check.is_animated and check.n_frames >= 8
        actual_frames = check.n_frames
        assert check.info['loop'] == 0
        assert check.size == (64, 64)
        total_duration = 0
        for index in range(check.n_frames):
            check.seek(index)
            assert 80 <= check.info['duration'] <= 240
            total_duration += check.info['duration']
            rgba = check.convert('RGBA')
            assert rgba.getchannel('A').getextrema() == (0, 255)
            box = rgba.getbbox()
            assert box and box[0] > 0 and box[1] > 0 and box[2] < 64 and box[3] < 64
    assert total_duration == count*80
    assert animated.stat().st_size < 250 * 1024
    def data(path):
        return 'data:image/gif;base64,' + base64.b64encode(path.read_bytes()).decode('ascii')
    presets.append({'id': kind, 'image': data(animated), 'still': data(still), 'frames': actual_frames, 'durationMs': total_duration})
    print(f'{kind}: {animated.stat().st_size} bytes, {count} frames, {count*80}ms; transparent and bounded')

module = ROOT / 'gif-presets.js'
module.write_text('// Generated by generate-gifs.py. Original monochrome activity GIFs.\nexport const GIF_PRESETS = Object.freeze(' + json.dumps(presets, ensure_ascii=False, separators=(',', ':')) + '.map(Object.freeze));\n', encoding='utf8')
